class CompatibleRow(dict):
    def __getitem__(self, key):
        if isinstance(key, int):
            return list(self.values())[key]
        return super().__getitem__(key)


class CompatibleResult:
    def __init__(self, result):
        self.result = result
        self.lastrowid = getattr(result, "lastrowid", None)

    def fetchone(self):
        row = self.result.fetchone()
        return CompatibleRow(row._mapping) if row is not None else None

    def fetchall(self):
        return [CompatibleRow(row._mapping) for row in self.result.fetchall()]


class DatabaseConnection:
    def __init__(self):
        self.connection = engine.connect()

    def execute(self, statement, parameters=()):
        if IS_POSTGRES:
            statement = statement.replace("?", "%s")
        return CompatibleResult(self.connection.exec_driver_sql(statement, tuple(parameters)))

    def commit(self):
        self.connection.commit()

    def __enter__(self):
        return self

    def __exit__(self, exception_type, exception_value, traceback):
        if exception_type:
            self.connection.rollback()
        self.connection.close()


def get_conn() -> DatabaseConnection:
    return DatabaseConnection()


