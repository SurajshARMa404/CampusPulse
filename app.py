@app.route("/api/login", methods=["POST"])
@csrf_required
def login() -> object:
    payload = request.get_json(silent=True) or {}
    username = str(payload.get("username", "")).strip()
    password = str(payload.get("password", ""))
    mfa_code = str(payload.get("mfa_code", "")).strip()
