@app.route("/api/signup", methods=["POST"])
@csrf_required
def signup() -> object:
    if IS_VERCEL and not HAS_PERSISTENT_DATABASE:
        return jsonify({"error": "Persistent database is not configured. Add DATABASE_URL in Vercel and redeploy."}), 503
    payload = request.get_json(silent=True) or {}
    username = str(payload.get("username", "")).strip()
    full_name = str(payload.get("full_name", username)).strip() or username
    email = str(payload.get("email", "")).strip().lower()
    password = str(payload.get("password", ""))
    role = str(payload.get("role", "student")).strip().lower()
    hostel = str(payload.get("hostel", "Unassigned")).strip() or "Unassigned"
    department = str(payload.get("department", "")).strip().upper()
    try:
        study_year = int(payload.get("study_year", 0))
    except (TypeError, ValueError):
        study_year = 0
    if len(username) < 3 or len(username) > 40 or not username.replace("_", "").isalnum():
        return jsonify({"error": "Choose a valid username."}), 400
    if role not in {"student", "admin"} or "@" not in email or len(password) < 10 or department != "CSE" or study_year not in (1, 2, 3, 4):
        return jsonify({"error": "Enter valid account details and a password of at least 10 characters."}), 400
    if role == "student" and not STUDENT_EMAIL_PATTERN.fullmatch(email):
        return jsonify({"error": "Students must use a college email like usernamecse@nsec.ac."}), 400
    with get_conn() as conn:
        try:
            count_query = "SELECT COUNT(*) AS count FROM users WHERE is_admin = ?"
            count_parameters = (1 if role == "admin" else 0,)
            if role == "student":
                count_query += " AND username <> 'guest'"
            count = conn.execute(count_query, count_parameters).fetchone()["count"]
            limit = MAX_ADMINS if role == "admin" else MAX_STUDENTS
            if count >= limit:
                return jsonify({"error": ("Admin" if role == "admin" else "Student") + " account limit reached."}), 409
            token_id = secrets.token_urlsafe(24)
            conn.execute(
                """INSERT INTO users
                   (username, email, full_name, role, hostel, token_id, password_hash, department, study_year, is_admin, is_verified, mfa_secret, created_at)
                   VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 1, ?, ?)""",
                (username, email, full_name, role, hostel, token_id, generate_password_hash(password), department, study_year,
                 1 if role == "admin" else 0, hashlib.sha256(secrets.token_urlsafe(24).encode()).hexdigest(), datetime.now(timezone.utc).isoformat()),
            )
            conn.commit()
        except IntegrityError:
            return jsonify({"error": "Unable to create account with those details."}), 400
        user = conn.execute("SELECT * FROM users WHERE token_id = ?", (token_id,)).fetchone()
    token = authenticate_user(user)
    app.logger.info("signup created username=%s role=%s", username, role)
    return jsonify({"message": "Account created.", "token": token, "role": role, "redirect": "admin.html" if role == "admin" else "home.html"})


@app.route("/api/signin", methods=["POST"])
@csrf_required
def signin() -> object:
    payload = request.get_json(silent=True) or {}
    username = str(payload.get("username", "")).strip()
    password = str(payload.get("password", ""))
    mfa_code = str(payload.get("mfa_code", "")).strip()
    with get_conn() as conn:
        user = conn.execute("SELECT * FROM users WHERE username = ? OR email = ?", (username, username.lower())).fetchone()
    if user is None or not check_password_hash(user["password_hash"], password):
        return jsonify({"error": "Invalid credentials."}), 401
    requested_role = str(payload.get("role", "student")).strip().lower()
    actual_role = "admin" if user["is_admin"] else "student"
    if requested_role != actual_role:
        return jsonify({"error": "The selected account type does not match this account."}), 403
    if user["is_admin"] and mfa_code:
        if not hmac.compare_digest(hashlib.sha256(mfa_code.encode()).hexdigest(), user["mfa_secret"]):
            return jsonify({"error": "Invalid admin MFA code."}), 401
    token = authenticate_user(user)
    return jsonify({"message": "Signed in.", "token": token, "role": "admin" if user["is_admin"] else "student", "redirect": "admin.html" if user["is_admin"] else "home.html"})


